REGLAS_NO_OBLIGATORIAS = frozenset(rid for rid, (estado, _) in CLASIFICACION_REGLAS.items() if estado == "No obligatoria")
REGLAS_OBLIGATORIAS = frozenset(rid for rid, (estado, _) in CLASIFICACION_REGLAS.items() if estado == "Obligatoria")

def estado_regla(regla):
    """Devuelve Obligatoria/No obligatoria según la clasificación SINIC acordada."""
    rid = str(regla or "").strip()
    return CLASIFICACION_REGLAS.get(rid, ("Sin clasificar", "Sin clasificar"))[0]

def clasificacion_regla(regla):
    """Devuelve Restrictiva, No Restrictiva o Diagnóstico."""
    rid = str(regla or "").strip()
    return CLASIFICACION_REGLAS.get(rid, ("Sin clasificar", "Sin clasificar"))[1]

def es_regla_obligatoria(regla):
    return estado_regla(regla) == "Obligatoria"
